export function parseQuestions(text) {
  return text
    .split('\n')
    .map((line) => line.split('|').map((s) => s.trim()).filter(Boolean))
    .filter((parts) => parts.length >= 3)
    .map(([q, correct, ...wrong]) => ({ q, correct, wrong: wrong.slice(0, 3) }));
}
